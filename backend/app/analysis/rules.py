UNCATEGORIZED = "未分类"


def categorize(transaction_type: str, counterparty: str, product: str = "") -> str:
    """按交易摘要 + 对手 + 商品信息分类，命中不了返回「未分类」。

    商品列常常才是真正说明「这是干什么的」的那一栏 —— 对手方可能只是个笼统的商户名
    （或像测试数据那样被统一改过），而商品里写着「单车」「食堂」「12306消费」。
    """

    text = f"{transaction_type} {counterparty} {product}".lower()
    for category, keywords in CATEGORY_RULES.items():
        if any(keyword.lower() in text for keyword in keywords):
            return category
    return UNCATEGORIZED
